-- LifeLink backend schema (Supabase / Postgres)
-- Self-contained: creates the base tables (patients, allergies,
-- emergency_contacts, medications, medical_history) if this is a fresh
-- project, then ADDITIVELY extends them with the columns the LifeLink
-- frontend needs, and adds two new tables (surgeries, medical_devices)
-- plus one unified table (clinical_records) backing the "Full Medical
-- Records" page's 8 categories (Visits / Diagnoses / Prescriptions /
-- Lab Reports / Surgeries / Vaccinations / Scans / Discharge Summaries).
--
-- Fingerprint/iris capture stay a pure frontend simulation
-- (see LifeLinkBiometrics) — nothing biometric is persisted here.
--
-- Safe to run multiple times (every statement is idempotent).
-- Run this once in the Supabase Dashboard: Project > SQL Editor > New query.

create extension if not exists pgcrypto;

-- base tables (created only if they don't already exist)
create table if not exists patients (
  patient_id     uuid primary key default gen_random_uuid(),
  lifelink_id    text not null,
  full_name      text not null,
  date_of_birth  date,
  gender         text,
  blood_group    text,
  phone          text,
  address        text,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create table if not exists allergies (
  allergy_id  uuid primary key default gen_random_uuid(),
  patient_id  uuid not null references patients(patient_id) on delete cascade,
  allergen    text,
  reaction    text,
  severity    text,
  created_at  timestamptz not null default now()
);

create table if not exists emergency_contacts (
  contact_id  uuid primary key default gen_random_uuid(),
  patient_id  uuid not null references patients(patient_id) on delete cascade,
  name        text,
  phone       text,
  priority    integer not null default 1,
  created_at  timestamptz not null default now()
);

create table if not exists medical_history (
  history_id  uuid primary key default gen_random_uuid(),
  patient_id  uuid not null references patients(patient_id) on delete cascade,
  condition   text,
  status      text,
  created_at  timestamptz not null default now()
);

create table if not exists medications (
  medication_id uuid primary key default gen_random_uuid(),
  patient_id    uuid not null references patients(patient_id) on delete cascade,
  medicine_name text,
  dosage        text,
  frequency     text,
  created_at    timestamptz not null default now()
);

-- patients: add fields the frontend collects that aren't in the schema yet
alter table patients add column if not exists email text;
alter table patients add column if not exists national_id text;
alter table patients add column if not exists photo_path text;
alter table patients add column if not exists emergency_notes text default '';

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'patients_lifelink_id_key'
  ) then
    alter table patients add constraint patients_lifelink_id_key unique (lifelink_id);
  end if;
end $$;

-- allergies: frontend groups allergies into drug / food / environmental
alter table allergies add column if not exists category text default 'drug';

-- medications: frontend tracks why a medication is prescribed
alter table medications add column if not exists purpose text;

-- surgeries: no existing table covers this
create table if not exists surgeries (
  surgery_id   uuid primary key default gen_random_uuid(),
  patient_id   uuid not null references patients(patient_id) on delete cascade,
  surgery_name text not null,
  surgery_date date,
  hospital     text,
  created_at   timestamptz not null default now()
);

-- medical_devices: no existing table covers this (pacemaker, insulin pump, etc.)
create table if not exists medical_devices (
  device_id   uuid primary key default gen_random_uuid(),
  patient_id  uuid not null references patients(patient_id) on delete cascade,
  device_name text not null,
  created_at  timestamptz not null default now()
);

-- clinical_records: unified store for the Full Medical Records page.
-- record_id is a human-readable id (e.g. REC-8942) generated by the backend,
-- matching the frontend's existing display convention.
create table if not exists clinical_records (
  record_id   text primary key,
  patient_id  uuid not null references patients(patient_id) on delete cascade,
  category    text not null,
  record_date date,
  title       text not null,
  doctor      text,
  facility    text,
  summary     text,
  code        text,
  badge       text,
  created_at  timestamptz not null default now()
);

-- Fingerprint data (fingerprint_templates, device_commands) does NOT live
-- here -- it's kept in a local Postgres on the machine running the backend
-- (LOCAL_DB_* in backend/.env), never in Supabase. See
-- fingerprint-device/db/schema.sql for that schema.

create index if not exists idx_clinical_records_patient on clinical_records(patient_id);
create index if not exists idx_clinical_records_category on clinical_records(category);
create index if not exists idx_allergies_patient on allergies(patient_id);
create index if not exists idx_medications_patient on medications(patient_id);
create index if not exists idx_medical_history_patient on medical_history(patient_id);
create index if not exists idx_surgeries_patient on surgeries(patient_id);
create index if not exists idx_medical_devices_patient on medical_devices(patient_id);
create index if not exists idx_emergency_contacts_patient on emergency_contacts(patient_id);
